package com.misaka.timelog.domain

/**
 * 「把一整批历史记录写进库」用的中间表示 —— **已经全部解析成 id 了**。
 *
 * ## 为什么要有这么一层
 *
 * 旧数据导入不是「一条一条按顺序插」那么简单：它要**整库替换**，
 * 而 `records` 这张表的不变式（一天恒 = 1440 分钟）由
 * `TimelineRepository` 独家维护 —— 这是 M1 就定下的规矩。
 *
 * 所以分工是：
 * - `LegacyImport`（数据来源那一侧）：读文件、解析 JSON、把**事项名/标签名**解析成 id
 * - `TimelineRepository`（不变式那一侧）：校验、补空白、一次性替换
 *
 * 中间用这两个类型对接 —— 它们只谈「几分钟到几分钟、挂哪个事项」，
 * 完全不知道数据是从 .xls 来的还是从云端拉的。
 */
data class ImportSegment(
    /** 当天第几分钟开始，`0..1439`。 */
    val startMin: Int,

    /** 当天第几分钟结束，`1..1440`。 */
    val endMin: Int,

    /** 挂靠的事项 id —— **必须已经解析过**，解析不出来的段不会走到这里。 */
    val itemId: String,

    /** 备注，一行。没有就是空串。 */
    val note: String,

    /** 这段挂了哪些标签。空列表 = 没有标签。 */
    val tagIds: List<String>,

    /**
     * 跨天切成多段时串起来用的 id。
     *
     * ⚠️ 旧数据里这个字段的完整性由**生成器**保证（见 `_import/build_import.py`
     * 「跨天链重标」那一段）：每条链至少两段、相邻两段必须同日相接、缝为 0。
     * 导入器**不再校验它** —— 它只影响 V2 那个「这件事连续了多久」的展示，
     * 不影响密铺、不影响统计，所以不配当拦下整包导入的理由。
     */
    val chainId: String?,
)

/** 某一天要写进去的全部真实记录段（**不含空白** —— 空白由仓库自己补）。 */
data class ImportDay(
    /** `'2026-10-14'` 形式。 */
    val day: String,

    /** 这天要写的段，顺序随意（仓库内部会排）。 */
    val segments: List<ImportSegment>,
)

/**
 * 一次整库替换的结果 —— 给界面报账用的。
 *
 * 故意只放「能对着数字复核」的量：天数、段数、补出的空白分钟数。
 * 用户看一眼就知道「哦，一年半确实差不多是这个量」，而不是一个「导入成功」完事。
 */
data class ImportReport(
    /** 写进去了几天。 */
    val days: Int,

    /** 写进去了几条**真实**记录（不含补出来的空白）。 */
    val segments: Int,

    /** 补出来几段空白。 */
    val gaps: Int,

    /** 补出来的空白一共多少分钟。 */
    val gapMinutes: Int,

    /**
     * 这些天加起来一共多少分钟。
     *
     * ⚠️ 它应当**恒等于** `days × 1440` —— 这就是密铺不变式的另一个说法。
     * 放进报告里是为了让这条恒等式在界面上也看得见，而不只在测试里。
     */
    val totalMinutes: Int,

    /**
     * 因为「不早于今天」被**跳过**的天。
     *
     * 为什么不直接拦下整包：这份数据是「导出那一刻」的快照，导出当天的那半天
     * 在 App 里另有记录，硬塞进去只会跟今天的实时状态打架。
     * 跳过、并在报告里说清楚跳了哪天，比整包失败更符合实际。
     */
    val skippedDays: List<String>,
)
